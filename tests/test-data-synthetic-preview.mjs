import assert from 'node:assert/strict';
import { profileTable, syntheticPreview, buildPrompt } from '../src/data-profile.js';
const table = profileTable([['name', 'value', 'binary', 'flag', 'category'], ['Zorabelle', 10, 0, true, 'yes'], ['Northwind', 100, 1, false, 'no']], 'source');
const preview = syntheticPreview(table);
assert.equal(preview.rows.length, 3);
for (const row of preview.rows) {
    assert.ok(!['Zorabelle', 'Northwind'].includes(row.column_1));
    assert.ok(row.column_2 >= 10 && row.column_2 <= 100 && Number.isInteger(row.column_2));
    assert.ok(![10, 100].includes(row.column_2));
    assert.ok([0, 1].includes(row.column_3));
    assert.equal(typeof row.column_4, 'boolean');
    assert.ok(!['yes', 'no'].includes(row.column_5));
}
assert.deepEqual(table.columns[4].previewOptions.genericValues, ['yes', 'no']);
table.columns[4].allowGenericReuse = true;
assert.ok(syntheticPreview(table).rows.every(row => ['yes', 'no'].includes(row.column_5)));
const collision = profileTable([['text'], ['  SYNTHETIC TEXT EXAMPLE 1. '], ['Synthetic text example 2.'], ['Ｓｙｎｔｈｅｔｉｃ text example 3.']], 'collision');
assert.equal(syntheticPreview(collision).rows[0].column_1, 'Synthetic text example 4.');
const exhausted = profileTable([['number'], [2], [3], [4]], 'exhausted');
assert.equal(syntheticPreview(exhausted).rows.length, 0);
assert.match(syntheticPreview(exhausted).issues[0], /No unused numeric/);
assert.equal(syntheticPreview(profileTable([['n'], [42]], 'constant')).rows.length, 0);
const identifiers = profileTable([['place'], ['Rotterdam'], ['Amsterdam']], 'places');
assert.deepEqual(identifiers.columns[0].previewOptions.genericValues, []);
assert.ok(!JSON.stringify(syntheticPreview(identifiers)).includes('Rotterdam'));
const empty = profileTable([['empty', 'text'], [null, 'keep']], 'empty');
assert.ok(syntheticPreview(empty).rows.every(row => row.column_1 === null));
const decimal = profileTable([['n'], [1.1], [1.9]], 'decimal');
assert.ok(syntheticPreview(decimal).rows.every(row => row.column_1 > 1.1 && row.column_1 < 1.9));
const context = { purpose: 'Tests', count: 10, relationships: 'None' };
assert.ok(!buildPrompt([table], context).includes('syntheticExamples'));
table.sharePreview = true;
assert.ok(buildPrompt([table], context).includes('syntheticExamples'));
assert.ok(!buildPrompt([table], context).includes('Zorabelle'));
exhausted.sharePreview = true;
assert.ok(!buildPrompt([exhausted], context).includes('syntheticExamples'));
console.log('Synthetic preview novelty, normalized collisions, binary/generic exceptions, numeric exhaustion and export checks passed.');
const { configureIdentifier, clearIdentifierSources } = await import('../src/data-profile.js');
const ids = profileTable([['id'], [' aa-00 '], ['AA-01'], ['ＡＡ-02']], 'ids');
configureIdentifier(ids.columns[0], 'AA-99');
assert.deepEqual(syntheticPreview(ids).rows.map(r => r.column_1), ['AA-03', 'AA-04', 'AA-05']);
assert.equal(new Set(ids.columns[0].identifierValues).size, 3);
configureIdentifier(ids.columns[0], 'aa-999');
assert.ok(syntheticPreview(ids).rows.every(r => /^[a-z]{2}-\d{3}$/.test(r.column_1)));
configureIdentifier(ids.columns[0], String.raw`\A\9-99`);
assert.equal(syntheticPreview(ids).rows[0].column_1, 'A9-00');
const numericIds = profileTable([['id'], ['000'], ['001'], ['002']], 'numeric ids');
configureIdentifier(numericIds.columns[0], '999');
assert.deepEqual(syntheticPreview(numericIds).rows.map(r => r.column_1), ['003', '004', '005']);
assert.ok(buildPrompt([numericIds], context).includes('"generatedType": "string"'));
assert.ok(buildPrompt([numericIds], context).includes('"identifierFormat": "999"'));
const fullIds = profileTable([['id'], ...Array.from({length: 8}, (_, i) => [String(i)])], 'full');
configureIdentifier(fullIds.columns[0], '9');
assert.equal(syntheticPreview(fullIds).rows.length, 0);
assert.match(fullIds.columns[0].identifierIssue, /Fewer than three/);
for (const mask of ['fixed', 'A'.repeat(65), 'AA?', 'AA\\']) {
    configureIdentifier(ids.columns[0], mask);
    assert.ok(ids.columns[0].identifierIssue, mask);
    assert.equal(syntheticPreview(ids).rows.length, 0);
}
configureIdentifier(ids.columns[0], '');
assert.equal(syntheticPreview(ids).rows.length, 3);
clearIdentifierSources();
configureIdentifier(ids.columns[0], 'AA-99');
assert.match(ids.columns[0].identifierIssue, /cleared/);
assert.equal(syntheticPreview(ids).rows.length, 0);
console.log('Identifier masks, normalization, escaping, leading zeros, uniqueness, exhaustion and source cleanup passed.');
